-- ---------------------------------------------------------------------
-- 006: the calendar, and reminders that cannot be sent twice
-- ---------------------------------------------------------------------
--
-- A design note, because it is the whole point of this file.
--
-- The calendar shows three kinds of thing: the weekly class sessions,
-- the quizzes, and one-off events like a term test. Only the last kind
-- is stored here.
--
-- Class sessions already exist as `classes.schedule_days` plus
-- start_time and end_time, and quizzes already carry opens_at and
-- closes_at. Copying either into an events table would create a second
-- copy of the truth that silently rots the first time the teacher moves
-- a class to a different day. So the calendar DERIVES those two, exactly
-- as the fee gate derives access from `payments` rather than keeping its
-- own flag. `calendar_events` holds only what has nowhere else to live.
--
-- The one exception is `cancelled_class`, which is an event that says a
-- derived session did not happen. That is new information -- there is no
-- column anywhere that records a single cancelled Saturday -- so it is
-- stored, and CalendarService subtracts it from the expansion.

CREATE TABLE IF NOT EXISTS calendar_events (
    id              INT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- A null class_id means the event is for everyone: a public holiday,
    -- or a notice to the whole school. A null institute_id with a set
    -- class_id is simply redundant; the class carries its own branch.
    class_id        INT UNSIGNED NULL,
    institute_id    INT UNSIGNED NULL,

    event_type      ENUM('exam','test','extra_class','cancelled_class','holiday','notice')
                    NOT NULL DEFAULT 'test',

    title           VARCHAR(255) NOT NULL,
    description     TEXT NULL,

    event_date      DATE NOT NULL,
    start_time      TIME NULL,
    end_time        TIME NULL,
    room            VARCHAR(100) NULL,

    -- Set on an exam or test so the student knows what to revise.
    syllabus        TEXT NULL,

    -- Whether reminders should go out for this event at all. A notice
    -- pinned for the month does not need waking anyone at 7am.
    remind          TINYINT(1) NOT NULL DEFAULT 1,

    event_status    ENUM('scheduled','cancelled') NOT NULL DEFAULT 'scheduled',

    created_by      INT UNSIGNED NULL,
    created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (id),
    KEY idx_cal_date (event_date),
    KEY idx_cal_class_date (class_id, event_date),
    KEY idx_cal_type (event_type),
    CONSTRAINT fk_cal_class     FOREIGN KEY (class_id)     REFERENCES classes(id)    ON DELETE CASCADE,
    CONSTRAINT fk_cal_institute FOREIGN KEY (institute_id) REFERENCES institutes(id) ON DELETE SET NULL,
    CONSTRAINT fk_cal_creator   FOREIGN KEY (created_by)   REFERENCES users(id)      ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ---------------------------------------------------------------------
-- What has already been reminded about
-- ---------------------------------------------------------------------
--
-- Reminders are generated by a job that may run every ten minutes, be
-- run twice by hand, or be run again after a crash halfway through. None
-- of that may produce a second notification for the same thing, so the
-- unique key below IS the de-duplication -- not a check-then-insert in
-- PHP, which two overlapping runs would both pass before either wrote.
--
-- `occurrence_at` is the exact datetime of the thing being reminded
-- about, which is what makes a weekly class distinguishable: the same
-- class_id reminds separately for each Saturday.
--
-- `lead_minutes` separates the day-before reminder from the hour-before
-- one, so both can exist for one occurrence and neither repeats.

CREATE TABLE IF NOT EXISTS reminder_dispatches (
    id              INT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Content announcements ride on the same table, and so inherit the
    -- same "exactly once" guarantee: re-saving a material must not
    -- notify thirty families a second time.
    source_type     ENUM('class_session','quiz_opens','quiz_closes','event',
                         'material_published','quiz_published') NOT NULL,
    source_id       INT UNSIGNED NOT NULL,
    occurrence_at   DATETIME NOT NULL,
    lead_minutes    SMALLINT UNSIGNED NOT NULL,

    recipient_type  ENUM('user','student','parent') NOT NULL,
    recipient_id    INT UNSIGNED NOT NULL,

    notification_id INT UNSIGNED NULL,
    created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),
    UNIQUE KEY uq_reminder_once (
        source_type, source_id, occurrence_at, lead_minutes,
        recipient_type, recipient_id
    ),
    KEY idx_rd_when (occurrence_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


